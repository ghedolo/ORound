"""Battery screen font for flame1_doom_spark: DejaVu Sans Bold (from matplotlib) rasterized to 8 bit alpha glyphs,
two sizes (percent and voltage), written to firmware/flame1_doom_spark/main/battery_font.h.

Usage: python scripts/make_battery_font.py
"""
import os

import matplotlib
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware", "flame1_doom_spark", "main", "battery_font.h")
FONT_PATH = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSans-Bold.ttf")
FONTS = [("BIG", 128, "0123456789%"), ("SMALL", 56, "0123456789.V")]


def build(size, chars):
    font = ImageFont.truetype(FONT_PATH, size)
    glyphs = []
    data = bytearray()
    for ch in chars:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")     # relative to the left end of the baseline
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        glyphs.append((ch, len(data), w, h, x0, y0, round(font.getlength(ch))))
        data += img.tobytes()
    cap = -font.getbbox("0", anchor="ls")[1]
    return glyphs, data, cap, round(font.getlength(" "))


with open(OUT, "w") as f:
    f.write("#pragma once\n\n")
    f.write("// Generated by scripts/make_battery_font.py: DejaVu Sans Bold, 8 bit alpha.\n")
    f.write("// DejaVu fonts: Bitstream Vera license (free use, modification and redistribution).\n\n")
    f.write("#include <stdint.h>\n\n")
    f.write("typedef struct {\n    uint32_t offset;   // first byte in the font data\n"
            "    uint8_t w, h;      // bitmap size\n    int8_t x0, y0;     // top left corner from the baseline start\n"
            "    uint8_t advance;   // pen advance\n} bfont_glyph_t;\n\n")
    f.write("typedef struct {\n    const char *chars;\n    const bfont_glyph_t *glyphs;\n    const uint8_t *data;\n"
            "    int cap;           // digit height in px\n    int space;         // advance of a space\n} bfont_t;\n\n")
    for name, size, chars in FONTS:
        glyphs, data, cap, space = build(size, chars)
        f.write("// %s: %d px, characters \"%s\"\n" % (name, size, chars))
        f.write("static const bfont_glyph_t BFONT_%s_GLYPHS[] = {\n" % name)
        for ch, off, w, h, x0, y0, adv in glyphs:
            f.write("    {%d, %d, %d, %d, %d, %d},  // %s\n" % (off, w, h, x0, y0, adv, ch))
        f.write("};\n\n")
        f.write("static const uint8_t BFONT_%s_DATA[%d] = {\n" % (name, len(data)))
        for i in range(0, len(data), 24):
            f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write("static const bfont_t BFONT_%s = {\"%s\", BFONT_%s_GLYPHS, BFONT_%s_DATA, %d, %d};\n\n"
                % (name, chars, name, name, cap, space))
        print("%s %d px: %d bytes, cap %d, \"100%%\" %d px" % (name, size, len(data), cap,
              sum(g[6] for g in glyphs if g[0] in "10%") + glyphs[0][6]))
print(OUT)
