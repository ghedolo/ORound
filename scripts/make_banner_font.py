"""Banner font for lifeAllStart: DejaVu Sans Bold (from matplotlib) rasterized to 8 bit alpha glyphs, written to
firmware/lifeAllStart/main/banner_font.h.

Usage: python scripts/make_banner_font.py [pixel size]
"""
import os
import sys

import matplotlib
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware", "lifeAllStart", "main", "banner_font.h")
CHARS = "0123456789abcdefghijklmnopqrstuvwxyz"
SIZE = int(sys.argv[1]) if len(sys.argv) > 1 else 96

font_path = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSans-Bold.ttf")
font = ImageFont.truetype(font_path, SIZE)
ascent, descent = font.getmetrics()

glyphs = []
data = bytearray()
for ch in CHARS:
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")     # relative to the left end of the baseline
    w, h = x1 - x0, y1 - y0
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    adv = round(font.getlength(ch))
    glyphs.append((ch, len(data), w, h, x0, y0, adv))
    data += img.tobytes()

with open(OUT, "w") as f:
    f.write("#pragma once\n\n")
    f.write("// Generated by scripts/make_banner_font.py: DejaVu Sans Bold %d px, 8 bit alpha, characters \"%s\".\n"
            % (SIZE, CHARS))
    f.write("// DejaVu fonts: Bitstream Vera license (free use, modification and redistribution).\n\n")
    f.write("#include <stdint.h>\n\n")
    f.write("typedef struct {\n    uint32_t offset;   // first byte in BANNER_FONT_DATA\n"
            "    uint8_t w, h;      // bitmap size\n    int8_t x0, y0;     // top left corner from the baseline start\n"
            "    uint8_t advance;   // pen advance\n} banner_glyph_t;\n\n")
    f.write("#define BANNER_FONT_SIZE    %d\n#define BANNER_FONT_ASCENT  %d\n#define BANNER_FONT_CHARS   \"%s\"\n\n"
            % (SIZE, ascent, CHARS))
    f.write("static const banner_glyph_t BANNER_GLYPHS[] = {\n")
    for ch, off, w, h, x0, y0, adv in glyphs:
        f.write("    {%d, %d, %d, %d, %d, %d},  // %s\n" % (off, w, h, x0, y0, adv, ch))
    f.write("};\n\n")
    f.write("static const uint8_t BANNER_FONT_DATA[%d] = {\n" % len(data))
    for i in range(0, len(data), 24):
        f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")

print("%s: %d bytes of glyph data" % (OUT, len(data)))
for word in ("life1", "conway", "penrose", "ts10", "ts12"):
    print("  %-8s %d px" % (word, sum(round(font.getlength(c)) for c in word)))
